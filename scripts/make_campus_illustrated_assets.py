"""Convert preserved AI PNG layers into fixed-size, tiled LVGL ROM constants.

Only crop/resize/format conversion; no generated substitute artwork or runtime decoder.
Run with Python + Pillow. Source files and full prompts live in assets/.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/pet-campus-illustrated'
RUNTIME = ART / 'runtime'
RUNTIME.mkdir(exist_ok=True)
code = ['/* Generated by scripts/make_campus_illustrated_assets.py. */', '#include "pet_campus_assets.h"']
header = ['#ifndef PET_CAMPUS_ASSETS_H', '#define PET_CAMPUS_ASSETS_H', '#include "lvgl.h"']
records = []

def digest(data):
    return hashlib.sha256(data).hexdigest().upper()

def emit(name, im, alpha=False):
    im = im.convert('RGBA' if alpha else 'RGB')
    colors = bytearray()
    alphas = bytearray()
    raw = im.tobytes()
    channels = 4 if alpha else 3
    for i in range(0, len(raw), channels):
        r, g, b = raw[i:i+3]
        rgb = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        colors.extend((rgb & 255, rgb >> 8))
        if alpha:
            alphas.append(raw[i+3])
    data = bytes(colors + alphas)
    code.append('static const LV_ATTRIBUTE_MEM_ALIGN uint8_t ' + name + '_data[] = {')
    code.extend(' ' + ','.join('0x%02x' % x for x in data[i:i+24]) + ',' for i in range(0, len(data), 24))
    w, h = im.size
    code.extend(['};', 'const lv_image_dsc_t ' + name + ' = {',
                 '.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_' + ('RGB565A8' if alpha else 'RGB565') +
                 ',.w=%d,.h=%d,.stride=%d},' % (w, h, w*2),
                 '.data_size=sizeof(' + name + '_data),.data=' + name + '_data};'])
    header.append('extern const lv_image_dsc_t ' + name + ';')
    im.save(RUNTIME / (name + '.png'))
    if alpha:
        a = im.getchannel('A')
        assert a.getextrema()[0] == 0 and a.getextrema()[1] == 255
    records.append({'symbol':name,'width':w,'height':h,'bytes':len(data),'sha256':digest(data)})

ground = Image.open(ART/'source/ground.png').convert('RGB').resize((560,880), Image.Resampling.LANCZOS)
ground.save(RUNTIME/'ground-complete.png')
assembled = Image.new('RGB', ground.size)
names = []
for row in range(4):
    for col in range(2):
        rect = (col*280,row*220,(col+1)*280,(row+1)*220)
        tile = ground.crop(rect)
        name = 'pc_ground_%d' % (row*2+col)
        emit(name, tile)
        names.append(name)
        assembled.paste(tile, rect[:2])
assert assembled.tobytes() == ground.tobytes(), 'ground tile seam mismatch'
approach = ground.crop((248,430,312,530))
emit('pc_approach', approach)
# This reusable paving tile keeps existing dorm/canteen approach lanes visible.
assembled.paste(approach, (48,640))
assembled.paste(approach, (448,640))
assembled.save(RUNTIME/'ground-navigation.png')
road_checks = 0
for x, y in ([(560,y) for y in range(120,700,5)] +
             [(x,y) for y in (160,560) for x in range(280,840,5)] +
             [(x,y) for x in (360,760) for y in range(460,561,5)]):
    r, g, b = assembled.getpixel((x-280,y+180))
    assert r >= g-4 and r > b, ('road center outside paving', x,y,r,g,b)
    road_checks += 1
code.append('const lv_image_dsc_t *const pc_ground[8]={' + ','.join('&'+n for n in names) + '};')
header.append('extern const lv_image_dsc_t *const pc_ground[8];')
crops = {}
for source, symbol, size in [('building','pc_building',(320,280)), ('tree','pc_tree',(180,250))]:
    im = Image.open(ART/('source/'+source+'.png')).convert('RGBA')
    alpha = im.getchannel('A')
    assert alpha.getextrema()[0] == 0, 'input must have real alpha'
    bounds = alpha.point(lambda x: 255 if x > 16 else 0).getbbox()
    assert bounds
    im = im.crop(bounds).resize(size, Image.Resampling.LANCZOS)
    emit(symbol, im, True)
    crops[source] = {'alpha_crop':bounds,'target_size':size}
header.append('#endif')
(ROOT/'src/pet_campus_assets.c').write_text('\n'.join(code)+'\n', encoding='utf-8')
(ROOT/'src/pet_campus_assets.h').write_text('\n'.join(header)+'\n', encoding='utf-8')
report = {'generated_by':'make_campus_illustrated_assets.py','sources':[
    {'path':str(p.relative_to(ROOT)).replace('\\','/'),'sha256':digest(p.read_bytes())} for p in sorted((ART/'source').glob('*.png'))],
    'images':records,'total_rom_pixel_bytes':sum(x['bytes'] for x in records),
    'ground_tiles_pixel_identical_to_full_image':True,'crop_and_resize':crops,
    'road_center_paving_checks':road_checks,
    'runtime_image_decoder_added':False,'full_map_ram_buffer_added':False}
(ART/'conversion.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'tiles':8,'rom_pixel_bytes':report['total_rom_pixel_bytes'],'seams':'PASS','alpha':'PASS'}))
