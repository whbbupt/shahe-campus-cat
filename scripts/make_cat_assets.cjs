const eyes = `<ellipse cx="14" cy="13" rx="3.6" ry="5.6" fill="${ink}"/><ellipse cx="70" cy="13" rx="3.6" ry="5.6" fill="${ink}"/><circle cx="13" cy="11" r="1.15" fill="#fff"/><circle cx="69" cy="11" r="1.15" fill="#fff"/>`;
const closed = `<path d="M8 14 Q14 19 20 14 M64 14 Q70 19 76 14" stroke="${ink}" stroke-width="2.5" fill="none"/>`;
const happy = `<path d="M8 16 Q14 7 20 16 M64 16 Q70 7 76 16" stroke="${ink}" stroke-width="2.5" fill="none"/>`;
const smile = `<path d="M42 29 L42 32 C41 37 35 37 34 33 M42 32 C43 37 49 37 50 33" stroke="${ink}" stroke-width="1.9" fill="none"/>`;
const sprites = [
  ['base',196,160,base],
  ['idle',88,44,eyes + smile],
  ['blink',88,44,closed + smile],
  ['happy',88,44,happy + smile],
  ['eat',88,44,eyes + `<path d="M36 30 Q42 28 48 30 C50 41 35 42 36 30" fill="${ink}"/><path d="M39 36 Q42 33 46 36 Q44 40 40 39" fill="${pink}"/>`],
  ['sad',88,44,eyes + `<path d="M8 3 L18 5 M66 5 L76 3 M38 36 Q42 32 46 36" fill="none" stroke="${ink}" stroke-width="1.9"/>`],
  ['heart',30,28,`<path d="M15 25 C10 20 2 15 2 9 C2 2 11 0 15 7 C19 0 28 2 28 9 C28 15 20 21 15 25 Z" fill="#df8e9c"/>`],
];
(async () => {
  const generated = ['/* Generated by scripts/make_cat_assets.cjs from original SVG artwork. */', '#include "pet_cat_assets.h"'];
  const declarations = ['#ifndef PET_CAT_ASSETS_H', '#define PET_CAT_ASSETS_H', '#include "lvgl.h"'];
  for (const [name,w,h,body] of sprites) {
    const svg = wrap(w,h,body);
    fs.writeFileSync(path.join(artwork,`cat-${name}.svg`),svg+'\n');
    const source = sharp(Buffer.from(svg),{density:288}).resize(w,h).ensureAlpha();
    await source.clone().png().toFile(path.join(artwork,`cat-${name}.png`));
    const {data} = await source.raw().toBuffer({resolveWithObject:true});
    // RGB565 color plane followed by one A8 plane, as specified by LVGL v9.
    // No indexed decoder or full-frame RGBA allocation is required at runtime.
    const bytes = Buffer.alloc(w*h*3);
    for(let i=0;i<w*h;i++){
      const color = ((data[i*4]>>3)<<11)|((data[i*4+1]>>2)<<5)|(data[i*4+2]>>3);
      bytes.writeUInt16LE(color,i*2); bytes[w*h*2+i]=data[i*4+3];
    }
    const symbol = `pet_cat_${name}`;
    generated.push(`static const LV_ATTRIBUTE_MEM_ALIGN uint8_t ${symbol}_data[] = {`);
    for(let i=0;i<bytes.length;i+=24) generated.push('    '+Array.from(bytes.subarray(i,i+24),v=>'0x'+v.toString(16).padStart(2,'0')).join(',')+',');
    generated.push('};',`const lv_image_dsc_t ${symbol} = {`,
      `    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = ${w}, .h = ${h}, .stride = ${w*2}},`,
      `    .data_size = sizeof(${symbol}_data), .data = ${symbol}_data`, '};');
    declarations.push(`extern const lv_image_dsc_t ${symbol};`);
  }
  declarations.push('#endif');
  fs.writeFileSync(path.join(root,'src','pet_cat_assets.c'),generated.join('\n')+'\n');
  fs.writeFileSync(path.join(root,'src','pet_cat_assets.h'),declarations.join('\n')+'\n');
  console.log('Generated original cat, five expressions, and heart; RGB565A8 data = 154680 bytes.');
})().catch(e=>{console.error(e);process.exit(1);});
