from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/pet-furniture/dorm-props.png'
ROOM_SIZES = [(20, 24), (38, 26), (30, 30)]


def pack_sprite(image, size):
    fitted = ImageOps.contain(image, size, Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', size)
    canvas.paste(fitted, ((size[0] - fitted.width) // 2, size[1] - fitted.height))
    rgb, alpha = bytearray(), bytearray()
    for r, g, b, a in canvas.getdata():
        rgb.extend((((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)).to_bytes(2, 'little'))
        alpha.append(a)
    return rgb + alpha


atlas = Image.open(SOURCE).convert('RGBA')
lines = ['/* Generated by scripts/make_pet_furniture_assets.py. */', '#include "pet_furniture_assets.h"']
for kind, sizes in [('room', ROOM_SIZES), ('preview', [(54, 46)] * 3)]:
    for index, (w, h) in enumerate(sizes):
        tile = atlas.crop((index * atlas.width // 3, 0, (index + 1) * atlas.width // 3, atlas.height))
        bounds = tile.getchannel('A').point(lambda value: 255 if value >= 96 else 0).getbbox()
        if bounds is None:
            raise ValueError(f'Furniture tile {index} is empty')
        data = pack_sprite(tile.crop(bounds), (w, h))
        name = f'furniture_{kind}_{index}'
        lines.append(f'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}[] = {{')
        for offset in range(0, len(data), 16):
            lines.append('    ' + ', '.join(f'0x{value:02x}' for value in data[offset:offset+16]) + ',')
        lines.append('};')
    lines.append(f'const lv_image_dsc_t pet_furniture_{kind}[3] = {{')
    for index, (w, h) in enumerate(sizes):
        name = f'furniture_{kind}_{index}'
        lines.append(f'    {{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8,')
        lines.append(f'                .w = {w}, .h = {h}, .stride = {w*2}}},')
        lines.append(f'     .data_size = sizeof({name}), .data = {name}}},')
    lines.append('};')
(ROOT / 'src/pet_furniture_assets.c').write_text('\n'.join(lines) + '\n', encoding='utf-8')
